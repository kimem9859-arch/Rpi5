def split_of(item_id):
    """🔒 dev = crc32 % 3 == 0 — 실행 전에 고정한 규칙(계획 관문 ②)."""
    return "dev" if zlib.crc32(item_id.encode("utf-8")) % 3 == 0 else "holdout"


